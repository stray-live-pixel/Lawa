// Команда lawa предоставляет офлайн-проверку workflow и встроенную инструкцию
// для будущего скилла Codex. Исполнение через Codex добавляется отдельно:
// успешная проверка схемы или вывод инструкции не означают запуск задач.
package main

import (
	"fmt"
	"io"
	"os"

	"github.com/stray-live-pixel/flows-2/internal/workflow"
)

const help = `Lawa — проверка JSON-workflow для задач AI-агентов.

Команды:
  lawa validate <workflow.json>  Проверить поля, ссылки и отсутствие циклов.
  lawa skill                     Вывести инструкцию для скилла Codex.
  lawa help                     Показать справку (также -h и --help).

Validate и skill не запускают агентов, не создают файлы и не требуют подключения к Codex.
Коды выхода: 0 — проверка/справка успешна; 2 — ошибка ввода или вывода.
Команды run и resume пока не реализованы.
`

// skillInstruction — самодостаточный текст будущего SKILL.md. Он описывает
// ответственность чата-инициатора и не обещает функций, которых ещё нет в CLI:
// перед запуском агент обязан проверить help и доступность run/resume. Поэтому
// текущую команду безопасно выпускать раньше координатора, не создавая ложный run.
const skillInstruction = `# Lawa: запуск workflow из чата Codex

Используй эту инструкцию только после явной просьбы пользователя запустить Lawa.
Обычное обсуждение или подготовка задачи не запускают workflow.

## Перед запуском

1. Убедись, что в текущем чате есть одно финальное, понятное описание задачи.
   Если его нет, сначала уточни и сформулируй задачу вместе с пользователем.
2. Возьми название workflow и необязательный комментарий из явного вызова.
3. Найди workflow по названию в рабочей папке проекта. Если совпадений нет или
   их несколько, не выбирай молча: попроси пользователя указать точный файл.
4. Выполни lawa validate <workflow.json>. При ошибке покажи её и не создавай run.
5. Выполни lawa help. Если команды run и resume ещё не доступны, сообщи, что
   установленная версия Lawa пока не умеет исполнять workflow, и остановись.

## Запуск и наблюдение

Запусти lawa run <workflow.json> --cwd <абсолютный-путь-проекта>, передав способом,
который описан в lawa help, финальную постановку, комментарий пользователя и ID
этого чата-инициатора. Не подменяй ID чата ID кубика и не создавай новый run для
продолжения прежнего.

Сохрани выведенный runId в контексте этого чата. Оставайся интерфейсом управления:
кратко сообщай, какие кубики выполняются, какие ждут зависимостей, где требуется
вмешательство пользователя и когда все кубики успешно завершились. Полные ответы
агентов находятся в отдельных чатах Codex.

Если Lawa остановлена, продолжай тот же запуск командой lawa resume <run-id>.
Не вызывай run повторно. Ошибка или отмена отдельного кубика не означает провал
всего workflow: пользователь продолжает тот же чат кубика, а Lawa ждёт его успеха.

## Формат workflow

JSON содержит непустые id и steps. Каждый элемент steps содержит уникальный id,
type со значением agent, непустой prompt и массив dependsOn с ID других кубиков.
Пустой dependsOn запускает кубик сразу; иначе он ждёт успеха всех зависимостей.
Порядок элементов массива не задаёт порядок исполнения.

## Память и безопасность

Lawa создаёт отдельный чат и отдельный файл памяти для каждого кубика. Агент читает
свою память в начале, обновляет её по ходу работы и перед завершением записывает
краткий итог, пути к результатам и ограничения. Он может изменять только собственный
файл memory/<threadId>.md. Чужую память, workflow.json, task.md и meta.json изменять
нельзя. Память коллег можно читать, но зависимый кубик всё равно ждёт их успеха.

Не обходи sandbox, ограничения организации и запросы авторизации Codex. Ctrl+C,
SIGTERM или ошибка координатора останавливают наблюдение и новые запуски, но не
являются разрешением отменять или дублировать уже созданные задачи.
`

// main отделяет код завершения процесса от проверяемой без subprocess логики CLI.
func main() {
	if err := execute(os.Args[1:], os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, "lawa:", err)
		os.Exit(2)
	}
}

// execute читает только выбранный файл и пишет результат в out. Ошибки передаются
// вызывающему коду; пустой список аргументов показывает справку без чтения файлов.
func execute(args []string, out io.Writer) error {
	if len(args) == 0 || (len(args) == 1 && (args[0] == "help" || args[0] == "-h" || args[0] == "--help")) {
		_, err := io.WriteString(out, help)
		return err
	}
	if args[0] == "skill" {
		if len(args) != 1 {
			return fmt.Errorf("использование: lawa skill")
		}
		_, err := io.WriteString(out, skillInstruction)
		return err
	}
	if args[0] != "validate" {
		return fmt.Errorf("неизвестная команда %q; см. lawa help", args[0])
	}
	if len(args) != 2 {
		return fmt.Errorf("использование: lawa validate <workflow.json>")
	}
	f, err := os.Open(args[1])
	if err != nil {
		return fmt.Errorf("открыть workflow: %w", err)
	}
	defer f.Close()
	w, err := workflow.Decode(f)
	if err != nil {
		return fmt.Errorf("проверить %q: %w", args[1], err)
	}
	// %q экранирует управляющие символы в пользовательском идентификаторе.
	_, err = fmt.Fprintf(out, "Workflow %q корректен; шагов: %d.\n", w.ID, len(w.Steps))
	return err
}
