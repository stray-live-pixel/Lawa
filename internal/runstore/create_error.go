package runstore

import (
	"errors"
	"fmt"
	"io/fs"
	"syscall"
)

// CreateError сообщает об отказе сохранения после создания новой папки run.
// RunDir — её абсолютный путь, Cause — исходная ошибка операции (всегда не nil),
// CleanupErr — отдельная ошибка удаления; nil означает, что RemoveAll завершился
// успешно. Ошибки проверки входа и подготовки root до создания run сюда не входят.
// Вызывающий код получает пустой Snapshot и может разобрать поля через errors.As,
// а системные причины — через errors.Is, без распознавания русского текста.
//
// Это возможный внешний сбой даже при корректном коде. Например, между записями
// файлов другой процесс занял оставшееся место, исчерпалась квота, task.md превысил
// лимит размера файла, изменились права папки или диск стал недоступен для записи.
// Отказ возможен и на Sync: успешный Write ещё не гарантирует сохранение на диск.
// Та же проблема может помешать удалению; нельзя обещать очистку, скрыв CleanupErr.
//
// Агенту следует сообщить полный текст ошибки: операция и путь сохраняются в Cause,
// а подсказка указывает, что проверить. Это не разрешение автоматически менять
// права, удалять чужие файлы или повторять запись без устранения причины. При отказе
// очистки удалять допустимо только указанный новый RunDir, не общий root.
// Повтор создания безопасен по контракту Create: исполнители ещё не запускались.
// Этот совет нельзя переносить на ошибки Load или сохранения уже работающих чатов:
// там повтор может создать второго исполнителя той же задачи (см. ErrInitiatorAsExecutor).
type CreateError struct {
	RunDir     string
	Cause      error
	CleanupErr error
}

// Error описывает причину, результат очистки и следующий шаг для человека/агента.
// Подсказка не заменяет исходную ошибку ОС и не обещает автоматического исправления.
func (e *CreateError) Error() string {
	message := fmt.Sprintf("не удалось сохранить новый запуск в %q: %v\n%s", e.RunDir, e.Cause, storageFailureHint(e.Cause))
	if e.CleanupErr == nil {
		message += "\nНезавершённая папка удалена. После устранения причины повторите создание запуска."
	} else {
		message += fmt.Sprintf("\nНе удалось удалить незавершённую папку %q: %v\n%s\n"+
			"После устранения причин удалите только эту папку и повторите создание запуска. Не удаляйте общее хранилище.",
			e.RunDir, e.CleanupErr, storageFailureHint(e.CleanupErr))
	}
	return message + "\nАгенты этого запуска ещё не запускались; старые запуски не затрагивались."
}

// Unwrap сохраняет обе причины для errors.Is/As. Поля позволяют отличить отказ
// сохранения от отказа очистки, даже если ОС вернула для них одинаковый код.
func (e *CreateError) Unwrap() error { return errors.Join(e.Cause, e.CleanupErr) }

// storageFailureHint переводит известные коды ОС в проверяемые действия.
// ENOSPC может означать и нехватку места, и исчерпание файловых записей; EFBIG —
// ограничение одного файла, а не заполненный диск. Неизвестную причину не угадываем.
func storageFailureHint(err error) string {
	switch {
	case errors.Is(err, syscall.ENOSPC):
		return "На диске нет места для данных или новых файлов. Проверьте свободное место и лимит числа файлов."
	case errors.Is(err, syscall.EDQUOT):
		return "Исчерпана дисковая квота. Освободите место в своей квоте или запросите её увеличение."
	case errors.Is(err, syscall.EFBIG):
		return "Превышен допустимый размер файла. Проверьте размер входных данных и лимит размера файла для процесса или файловой системы."
	case errors.Is(err, fs.ErrPermission):
		return "Нет прав на операцию. Проверьте владельца и права указанной папки; при необходимости запросите доступ."
	case errors.Is(err, syscall.EROFS):
		return "Файловая система доступна только для чтения. Проверьте подключение диска и доступность хранилища для записи."
	case errors.Is(err, syscall.EIO):
		return "Ошибка ввода-вывода. Проверьте состояние и подключение диска; не повторяйте запись до устранения сбоя."
	default:
		return "Причина требует диагностики. Проверьте указанную операцию, путь и доступность хранилища."
	}
}
