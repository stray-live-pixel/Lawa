package coordinator

import "encoding/json/v2"

// resultInstructions задаёт одинаковый договор отчёта для legacy и посещений v2.
// Текст встроен в бинарник: наличие личных скиллов mom/concise у агента не нужно.
// Маркер отличает итог от промежуточных сообщений в сохранённом журнале; отчёт
// описывает работу, но никогда не меняет технический статус или выбранный маршрут.
const resultInstructions = `Финальный ответ начни с «Итог:» и дай короткий понятный отчёт по правилам mom и concise.
Сразу скажи, что получилось. Затем коротко укажи, что сделано, как проверено и что осталось или требует внимания.
Пиши простыми словами, без вступления, повторов и пересказа хода работы. Неизбежный термин сразу объясни.
Сохрани важные условия, ограничения и ссылки или пути к результатам. Не выдумывай выполненные действия и проверки.
Не используй маркер «Итог:» в промежуточных сообщениях. Такой же итог сохрани в своей памяти.`

// resultContext передаёт Markdown как строку JSON: кавычки и переносы в отчёте
// остаются данными свойства, а не меняют разметку служебного контекста.
func resultContext(result string) string {
	if result == "" {
		return ""
	}
	encoded, _ := json.Marshal(result)
	return "  result (Markdown): " + string(encoded)
}
